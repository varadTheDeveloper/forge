"""Generates runtime/EncodingTables.inc (Phase 10.1, PHASE10_DESIGN.md).

The input is a folder with the WHATWG Encoding Standard's data files, taken
unchanged from https://github.com/whatwg/encoding:

    encodings.json           every encoding and its labels
    index-<name>.txt         one per single-byte encoding

Usage (from the repository root):

    python tools/gen-encoding-tables.py <folder> > runtime/EncodingTables.inc

The output lists every encoding Forge's TextDecoder supports (UTF-8, the
single-byte encodings, x-user-defined, UTF-16BE and UTF-16LE), the 128-entry
table of each single-byte encoding, and every label of the standard sorted
for a binary search. Labels of the multi-byte CJK encodings are kept and
marked "unsupported", so TextDecoder can name them in its RangeError; labels
of the "replacement" encoding are marked as such (the standard makes
TextDecoder refuse them too).
"""

import json
import os
import sys

UNSUPPORTED = 0xFF
REPLACEMENT = 0xFE


def read_index(path):
    """The 128 code points of a single-byte index, and its Identifier line."""
    table = [0] * 128
    identifier = "unknown"

    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()

            if line.startswith("# Identifier:"):
                identifier = line.split(":", 1)[1].strip()
                continue

            if not line or line.startswith("#"):
                continue

            fields = line.split()
            pointer = int(fields[0])
            code_point = int(fields[1], 16)

            if not 0 <= pointer < 128 or not 0 < code_point <= 0xFFFF:
                raise SystemExit(f"{path}: unexpected entry {line!r}")

            table[pointer] = code_point

    return table, identifier


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen-encoding-tables.py <folder with encodings.json and index-*.txt>")

    folder = sys.argv[1]

    with open(os.path.join(folder, "encodings.json"), encoding="utf-8") as f:
        sections = json.load(f)

    encodings = []  # (name, kind, table index or -1)
    tables = []     # (name, 128 code points; 0 = no mapping)
    labels = []     # (label, encoding id)

    for section in sections:
        heading = section["heading"]

        for encoding in section["encodings"]:
            name = encoding["name"]

            if name == "replacement":
                encoding_id = REPLACEMENT
            elif heading == "The Encoding":
                encoding_id = len(encodings)
                encodings.append((name, "Utf8", -1))
            elif heading == "Legacy single-byte encodings":
                index_name = "iso-8859-8" if name == "ISO-8859-8-I" else name.lower()
                table_index = next((i for i, t in enumerate(tables) if t[0] == index_name), -1)

                if table_index < 0:
                    table_index = len(tables)
                    table, identifier = read_index(
                        os.path.join(folder, f"index-{index_name}.txt"))
                    tables.append((index_name, table, identifier))

                encoding_id = len(encodings)
                encodings.append((name, "SingleByte", table_index))
            elif name == "UTF-16BE":
                encoding_id = len(encodings)
                encodings.append((name, "Utf16Be", -1))
            elif name == "UTF-16LE":
                encoding_id = len(encodings)
                encodings.append((name, "Utf16Le", -1))
            elif name == "x-user-defined":
                encoding_id = len(encodings)
                encodings.append((name, "XUserDefined", -1))
            else:
                encoding_id = UNSUPPORTED  # the CJK multi-byte encodings

            for label in encoding["labels"]:
                labels.append((label, encoding_id))

    labels.sort(key=lambda entry: entry[0].encode("ascii"))

    for a, b in zip(labels, labels[1:]):
        if a[0] == b[0]:
            raise SystemExit(f"duplicate label {a[0]!r}")

    out = sys.stdout
    out.write("// Generated by tools/gen-encoding-tables.py from the WHATWG Encoding\n")
    out.write("// Standard's encodings.json and index files. Do not edit by hand.\n")
    out.write("// Included once, by runtime/Encoding.cpp.\n\n")

    out.write(f"constexpr Size kEncodingCount = {len(encodings)};\n")
    out.write(f"constexpr u8 kLabelUnsupported = 0x{UNSUPPORTED:02X};\n")
    out.write(f"constexpr u8 kLabelReplacement = 0x{REPLACEMENT:02X};\n\n")

    out.write("constexpr EncodingRecord kEncodings[kEncodingCount] = {\n")
    for name, kind, table_index in encodings:
        out.write(f'    {{"{name.lower()}", Kind::{kind}, {table_index}}},\n')
    out.write("};\n\n")

    out.write(f"// Bytes 0x80-0xFF of each single-byte encoding; 0 means no mapping.\n")
    out.write(f"constexpr char16_t kSingleByteTables[{len(tables)}][128] = {{\n")
    for name, table, identifier in tables:
        out.write(f"    // {name} (index Identifier {identifier})\n    {{\n")
        for row in range(0, 128, 8):
            values = ", ".join(f"0x{v:04X}" for v in table[row:row + 8])
            out.write(f"        {values},\n")
        out.write("    },\n")
    out.write("};\n\n")

    out.write("// Every label, sorted by byte value for a binary search.\n")
    out.write(f"constexpr LabelRecord kLabels[{len(labels)}] = {{\n")
    for label, encoding_id in labels:
        out.write(f'    {{"{label}", 0x{encoding_id:02X}}},\n')
    out.write("};\n")


if __name__ == "__main__":
    main()
