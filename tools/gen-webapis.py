"""Embeds runtime/WebApis.js in C++ as runtime/WebApis.js.inc (Phase 10.1).

Usage (from the repository root):

    python tools/gen-webapis.py            rewrite runtime/WebApis.js.inc
    python tools/gen-webapis.py --check    exit 1 if it is out of date (CI)

The script is split into raw string literals of at most 8000 bytes, cut at
line ends (MSVC refuses a single string literal over 16380 bytes), which
runtime/WebApis.cpp joins before compiling. The script must be ASCII so the
bytes mean the same to every compiler.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "runtime", "WebApis.js")
OUTPUT = os.path.join(ROOT, "runtime", "WebApis.js.inc")
DELIMITER = "FORGEJS"
PIECE_LIMIT = 8000


def generate():
    with open(SOURCE, encoding="utf-8", newline=None) as f:
        text = f.read()

    if any(ord(c) > 0x7E or (ord(c) < 0x20 and c != "\n") for c in text):
        raise SystemExit("runtime/WebApis.js must be printable ASCII (use \\u escapes)")

    if ")" + DELIMITER + '"' in text:
        raise SystemExit("runtime/WebApis.js contains the raw string delimiter")

    pieces = []
    current = ""

    for line in text.splitlines(keepends=True):
        if len(current) + len(line) > PIECE_LIMIT and current:
            pieces.append(current)
            current = ""

        current += line

    if current:
        pieces.append(current)

    out = [
        "// Generated by tools/gen-webapis.py from runtime/WebApis.js. Do not edit\n",
        "// by hand: change WebApis.js and run the generator (CI checks the two\n",
        "// match). Included once, by runtime/WebApis.cpp.\n",
        "\n",
        "constexpr const char* kWebApisSourcePieces[] = {\n",
    ]

    for piece in pieces:
        out.append(f'R"{DELIMITER}({piece}){DELIMITER}",\n')

    out.append("};\n")
    return "".join(out)


def main():
    content = generate()

    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        try:
            with open(OUTPUT, encoding="utf-8", newline=None) as f:
                current = f.read()
        except FileNotFoundError:
            current = None

        if current != content:
            print("runtime/WebApis.js.inc is out of date: run python tools/gen-webapis.py")
            return 1

        print("runtime/WebApis.js.inc is up to date")
        return 0

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)

    return 0


if __name__ == "__main__":
    sys.exit(main())
